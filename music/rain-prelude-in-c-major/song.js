// Партитура «Rain Prelude in C major»: 4/4, 76 BPM, 36 тактов. Каждый такт - один аккорд, разложенный восьмыми по кругу
// (бас, тенор, три верхних голоса - дважды), как капли; со второй половины из верхнего голоса растёт мелодия, входят струнные.
(function (g) {
  const BPM = 76, BEAT = 60 / BPM, BAR = 4 * BEAT;
  const notes = [], chords = [], sections = [], drums = [];
  const N = (bar, beat, d, m, v, i) => notes.push({ t: (bar * 4 + beat) * BEAT, d: d * BEAT, m, v: Math.min(1, v), i });
  // аккорд = [название, бас, тенор, три верхних голоса] (MIDI)
  const C = (name, b, t, s1, s2, s3) => ({ name, v: [b, t, s1, s2, s3] });
  const P = [
    C('C', 48, 55, 64, 67, 72), C('Am/C', 48, 57, 64, 69, 72), C('Fmaj7/C', 48, 57, 64, 65, 69), C('G7/B', 47, 55, 62, 65, 71),
    C('C', 48, 55, 64, 67, 72), C('Em/B', 47, 55, 64, 67, 71), C('Am', 45, 57, 64, 69, 72), C('D7/A', 45, 54, 62, 66, 72),
    C('G/B', 47, 55, 62, 67, 71), C('Gm6/B♭', 46, 55, 62, 64, 70), C('F/A', 45, 57, 65, 69, 72), C('Fm/A♭', 44, 56, 65, 68, 72),
    C('C/G', 43, 55, 64, 67, 72), C('G7', 43, 53, 62, 65, 71), C('C', 48, 55, 64, 67, 72), C('C7', 48, 55, 64, 67, 70),
    C('Fmaj7', 41, 57, 64, 65, 69), C('Dm7/F', 41, 57, 60, 62, 65), C('E7/G♯', 44, 56, 62, 64, 68), C('Am', 45, 57, 60, 64, 69),
    C('F', 41, 53, 60, 65, 69), C('G', 43, 55, 62, 67, 71), C('Em', 40, 55, 59, 64, 67), C('A7', 45, 55, 61, 64, 67),
    C('Dm', 38, 53, 62, 65, 69), C('B°/D', 38, 53, 59, 62, 65), C('C/E', 40, 55, 60, 64, 72), C('Fmaj7', 41, 57, 64, 65, 69),
    C('C/G', 43, 55, 64, 67, 72), C('G7sus', 43, 55, 60, 65, 70), C('G7', 43, 55, 62, 65, 71), C('C', 36, 55, 64, 67, 72),
    C('F/C', 36, 53, 65, 69, 72), C('G7/C', 36, 53, 62, 65, 71), C('C', 36, 52, 60, 64, 67), C('C', 36, 48, 55, 64, 72)];
  sections.push({ bar: 0, name: 'RAIN' }, { bar: 8, name: 'DRIFT' }, { bar: 16, name: 'SONG' }, { bar: 24, name: 'STORM' }, { bar: 30, name: 'CLEARING' });
  P.forEach((c, b) => chords.push({ t: b * BAR, name: c.name }));
  // мелодия верхнего голоса с 16-го такта: [такт, доля, длительность, нота]
  const MEL = [[16, 0, 2, 76], [16, 2, 2, 77], [17, 0, 3, 74], [17, 3, 1, 72], [18, 0, 2, 71], [18, 2, 2, 74], [19, 0, 4, 72],
    [20, 0, 2, 77], [20, 2, 2, 81], [21, 0, 3, 79], [21, 3, 1, 77], [22, 0, 2, 76], [22, 2, 2, 79], [23, 0, 4, 76],
    [24, 0, 2, 81], [24, 2, 2, 77], [25, 0, 2, 74], [25, 2, 2, 77], [26, 0, 3, 79], [26, 3, 1, 76], [27, 0, 4, 81],
    [28, 0, 2, 79], [28, 2, 2, 76], [29, 0, 2, 77], [29, 2, 2, 74], [30, 0, 4, 74], [31, 0, 4, 72]];
  P.forEach((c, b) => { const [bs, tn, s1, s2, s3] = c.v; const last = b >= 34;
    const dyn = b < 8 ? 0.36 + b * 0.01 : b < 16 ? 0.42 : b < 24 ? 0.46 : b < 30 ? 0.52 + (b - 24) * 0.015 : 0.42 - (b - 30) * 0.03;
    if (!last) for (let h = 0; h < 2; h++) { const o = h * 2;
      N(b, o, 2, bs, dyn * 1.05, 'lh'); N(b, o + 0.5, 1.5, tn, dyn * 0.8, 'lh');
      [s1, s2, s3, s2].forEach((m, k) => N(b, o + 1 + k * 0.25, 0.9 - k * 0.15, m, dyn * (k === 2 ? 0.95 : 0.78), 'rh')); }
    else if (b === 34) { [bs, tn].forEach((m) => N(b, 0, 4, m, 0.36, 'lh')); [s1, s2, s3].forEach((m, k) => N(b, 1 + k * 0.5, 3 - k * 0.5, m, 0.33, 'rh')); }
    else { [bs, tn].forEach((m) => N(b, 0, 6, m, 0.34, 'lh')); [s1, s2, s3].forEach((m) => N(b, 0, 6, m, 0.3, 'rh')); N(b, 1, 3, 84, 0.18, 'bell'); }
    if (b >= 16 && b < 34) [tn + 12, s2].forEach((m) => N(b, 0, 4, m, b >= 24 && b < 30 ? 0.3 : 0.2, 'str'));
    if (b >= 24 && b < 30) N(b, 0, 4, bs - 12 >= 28 ? bs - 12 : bs, 0.34, 'bass');
    if (b >= 30) N(b, 0, b >= 34 ? 6 : 4, 36, 0.3, 'cello'); });
  MEL.forEach(([b, x, d, m]) => { N(b, x, d * 0.97, m + 12, 0.56, 'rh'); if (b >= 24 && b < 30) N(b, x, d * 0.97, m, 0.3, 'cello'); });
  // капли-колокольчики в начале
  [[1, 3.5, 88], [3, 2.5, 91], [5, 3.5, 86], [7, 1.5, 93]].forEach(([b, x, m]) => N(b, x, 1, m, 0.16, 'bell'));
  drums.push({ t: 24 * BAR, k: 'boom', v: 0.35 });
  notes.sort((a, b) => a.t - b.t);
  const spell = { 0: [0, ''], 1: [0, '♯'], 2: [1, ''], 3: [2, '♭'], 4: [2, ''], 5: [3, ''], 6: [3, '♯'], 7: [4, ''], 8: [5, '♭'], 9: [5, ''], 10: [6, '♭'], 11: [6, ''] };
  g.SONG = { BPM, BEAT, BAR, notes, chords, sections, drums, bars: P.length, DUR: 35 * BAR + 6.5, key: 'C MAJOR', title: 'Rain Prelude in C major', word: 'RAIN PRELUDE', sub: 'IN  C  MAJOR', spell, keysig: [] };
})(typeof window !== 'undefined' ? window : globalThis);
